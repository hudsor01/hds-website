describe('escaping', () => {
	test('mdCode keeps untrusted text in one safe code span', () => {
		expect(mdCode('@octocat | `x`\nnext')).toBe("`@octocat \\| 'x' next`")
		expect(mdCode('a\r\n\r\nb')).toBe('`a b`')
	})

	test('queries render only inside code spans', () => {
		const shown = [strikingRow('#12 fix @team'), strikingRow('a|b `c`')]
		const body = renderReport(model({ striking: { shown, total: 2 } }))
		expect(body).toContain('`#12 fix @team`')
		expect(body.replace(/`[^`]*`/g, '')).not.toMatch(/#12|@team/)
		const row = lines(body).find(l => l.includes('a\\|b'))
		expect(row?.split(/(?<!\\)\|/)).toHaveLength(8)
	})
})

describe('size cap', () => {
	test('stays under 60,000 bytes and keeps every flagged post', () => {
		const coverage = 'Crawled currently not indexed '.repeat(14).slice(0, 400)
		const posts = Array.from({ length: 150 }, (_, i) => {
			const slug = `post-${String(i).padStart(3, '0')}`
			const status = indexed(slug, { coverageState: coverage })
			return i % 30 === 0
				? post(slug, { ok: true, status: { ...status, verdict: 'NEUTRAL' } })
				: post(slug, { ok: true, status })
		})
		expect(posts.filter(p => p.reasons.length > 0)).toHaveLength(5)
		const shown = Array.from({ length: 50 }, (_, i) =>
			strikingRow(`query ${i}`)
		)
		const body = renderReport(
			model({ posts, totalRecent: 150, striking: { shown, total: 50 } })
		)
		expect(Buffer.byteLength(body, 'utf8')).toBeLessThanOrEqual(60_000)
		expect(section(body, '## Recent posts')).toContain(SIZE_NOTE)
		const needs = section(body, '## Needs attention')
		for (const p of posts.filter(p => p.reasons.length > 0)) {
			expect(needs).toContain(`[/blog/${p.slug}]`)
		}
		expect(needs).not.toContain(SIZE_NOTE)
		expect(section(body, '## Striking distance')).not.toContain(SIZE_NOTE)
	})

	test('drops striking rows before flagged rows when it must', () => {
		const coverage = 'x'.repeat(400)
		const posts = Array.from({ length: 150 }, (_, i) =>
			post(`flagged-${i}`, {
				ok: true,
				status: { verdict: 'NEUTRAL', coverageState: coverage }
			})
		)
		const shown = Array.from({ length: 50 }, (_, i) =>
			strikingRow(`query ${i}`)
		)
		const body = renderReport(
			model({ posts, totalRecent: 150, striking: { shown, total: 50 } })
		)
		expect(Buffer.byteLength(body, 'utf8')).toBeLessThanOrEqual(60_000)
		expect(lines(section(body, '## Striking distance'))).toContain(
			`50 rows ${SIZE_NOTE}`
		)
		expect(lines(section(body, '## Recent posts'))).toContain(
			`150 rows ${SIZE_NOTE}`
		)
		expect(section(body, '## Needs attention')).toContain(SIZE_NOTE)
		expect(section(body, '## Needs attention')).toContain('[/blog/flagged-0]')
	})

	test('a body under the cap drops nothing', () => {
		expect(renderReport(model())).not.toContain(SIZE_NOTE)
	})
})

describe('copy rules', () => {
	test('template text has no dash, emoji or comma before and', () => {
		const body = renderReport(
			model({
				totalRecent: 170,
				skippedByCap: 20,
				rowLimitHit: true,
				brand: { clicks: 1, impressions: 2, rowLimitHit: true }
			})
		)
		const empty = renderReport(
			model({
				posts: [],
				striking: { shown: [], total: 0 },
				window: null,
				brand: null
			})
		)
		for (const out of [body, empty]) {
			expect(out).not.toMatch(DASH_RE)
			expect(out).not.toMatch(EMOJI_RE)
			expect(countCommaBeforeAnd(out)).toBe(0)
		}
	})
})
