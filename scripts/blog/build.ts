/**
 * Compile content/blog/*.md into src/lib/_generated/blog-posts.ts, a typed,
 * gitignored module holding every published post. It is imported by the
 * public blog data layer (src/lib/blog.ts) and bundled into the server build,
 * so serving the blog needs no database and no runtime filesystem access.
 *
 *   bun run blog:build
 *
 * Runs automatically before `build`, `dev`, `typecheck` and `test:unit` (see
 * package.json), so the gitignored output is always fresh. Any parse failure
 * or validation ERROR (same rules as blog:validate) throws, failing the build
 * loudly instead of shipping an empty or partial blog. Links to scheduled
 * posts render as plain text until their date; the daily scheduled-publish
 * rebuild turns them into links on the day the target goes live.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { stripMarkdown } from '@/lib/strip-markdown'
import type { CompiledBlogPost } from '@/types/blog'
import {
	bodyToHtml,
	CONTENT_DIR,
	computeReadingTime,
	isLive,
	listPostFiles,
	type ParsedPost,
	parsePost,
	validatePost
} from './lib'

const GENERATED_DIR = join(process.cwd(), 'src/lib/_generated')
const POSTS_FILE = join(GENERATED_DIR, 'blog-posts.ts')
const HEADER = `// AUTO-GENERATED by scripts/blog/build.ts from content/blog/*.md.
// Do not edit and do not commit (gitignored). Run \`bun run blog:build\`.`

/** Newest first; slug breaks ties so same-day posts have a stable order. */
function compareByPublishedDesc(
	a: CompiledBlogPost,
	b: CompiledBlogPost
): number {
	return (
		Date.parse(b.publishedAt) - Date.parse(a.publishedAt) ||
		a.slug.localeCompare(b.slug)
	)
}

function compilePost(
	{ slug, data, body }: ParsedPost,
	linkable: (slug: string) => boolean
): CompiledBlogPost {
	const title = stripMarkdown(data.title)
	if (!title) {
		throw new Error(`${slug}: title is empty after stripping markdown`)
	}
	return {
		slug,
		title,
		excerpt: stripMarkdown(data.excerpt),
		content: bodyToHtml(body, data.bodyFormat ?? 'markdown', linkable),
		featureImage: data.featureImage || null,
		publishedAt: new Date(data.publishedAt).toISOString(),
		readingTime:
			data.readingTime && data.readingTime > 0
				? data.readingTime
				: computeReadingTime(body),
		featured: data.featured ?? false,
		tagSlugs: data.tags,
		authorSlug: data.author
	}
}

function failureMessage(failures: string[]): string {
	return `blog:build failed for ${failures.length} issue(s):\n  ${failures.join('\n  ')}`
}

/**
 * Parse and validate every post in `dir`, drafts and scheduled posts
 * included. Any parse failure or validation ERROR throws, listing each one.
 */
export function loadPosts(dir: string = CONTENT_DIR): ParsedPost[] {
	const failures: string[] = []
	const posts: ParsedPost[] = []

	for (const file of listPostFiles(dir)) {
		let parsed: ParsedPost
		try {
			parsed = parsePost(file, dir)
		} catch (error) {
			failures.push(
				`${file}: cannot parse (${error instanceof Error ? error.message : String(error)})`
			)
			continue
		}

		const errors = validatePost(parsed).filter(v => v.severity === 'error')
		if (errors.length > 0) {
			for (const v of errors) {
				failures.push(`${file}: [${v.rule}] ${v.message}`)
			}
			continue
		}
		posts.push(parsed)
	}

	if (failures.length > 0) {
		throw new Error(failureMessage(failures))
	}
	return posts
}

/**
 * Parse, validate, and compile every post in `dir`. Drafts
 * (`published: false`) and scheduled posts (publishedAt after `now`) are
 * validated but excluded from the output, and links to them render as text.
 */
export function compilePosts(
	dir: string = CONTENT_DIR,
	now: Date = new Date()
): CompiledBlogPost[] {
	const parsed = loadPosts(dir).filter(p => isLive(p.data, now))
	const live = new Set(parsed.map(p => p.slug))
	const failures: string[] = []
	const posts: CompiledBlogPost[] = []

	for (const p of parsed) {
		try {
			posts.push(compilePost(p, slug => live.has(slug)))
		} catch (error) {
			failures.push(error instanceof Error ? error.message : String(error))
		}
	}

	if (failures.length > 0) {
		throw new Error(failureMessage(failures))
	}
	if (posts.length === 0) {
		throw new Error(`blog:build found no published posts in ${dir}`)
	}
	return posts.sort(compareByPublishedDesc)
}

export function renderModule(posts: CompiledBlogPost[]): string {
	return `${HEADER}
import type { CompiledBlogPost } from '@/types/blog'

export const BLOG_POSTS: readonly CompiledBlogPost[] = ${JSON.stringify(posts, null, '\t')}
`
}

/** Write only when the content changed, so unchanged builds stay cached. */
function writeIfChanged(file: string, source: string): boolean {
	const current = existsSync(file) ? readFileSync(file, 'utf8') : ''
	if (current === source) {
		return false
	}
	mkdirSync(dirname(file), { recursive: true })
	writeFileSync(file, source)
	return true
}

/**
 * BLOG_CONTENT_DIR swaps in another post directory. The visual regression
 * run points it at tests/fixtures/blog so /blog renders the same posts no
 * matter what has been published or scheduled since the baselines were made.
 */
function contentDir(): string {
	const override = process.env.BLOG_CONTENT_DIR
	return override ? resolve(override) : CONTENT_DIR
}

function main(): void {
	const dir = contentDir()
	const posts = compilePosts(dir)
	const changed = writeIfChanged(POSTS_FILE, renderModule(posts))
	console.warn(
		`blog:build - ${posts.length} published posts${dir === CONTENT_DIR ? '' : ` from ${dir}`} -> src/lib/_generated/blog-posts.ts${changed ? '' : ' (unchanged)'}`
	)
}

if (import.meta.main) {
	main()
}
