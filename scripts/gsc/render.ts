/**
 * Markdown for the rolling "Search Console weekly report" issue body (D9).
 * Pure: takes a ReportModel and returns a string. Search queries and Google
 * strings go through mdCode so they cannot ping users or break tables. The
 * body is held under BODY_BYTE_CAP with every dropped row counted (D15 C9).
 */
import {
	BODY_BYTE_CAP,
	BRAND_TERMS,
	LOOKBACK_DAYS,
	MAX_INSPECTIONS,
	PROBE_DAYS,
	ROW_LIMIT,
	STRIKING_MAX,
	STRIKING_MIN
} from './config'
import { normalizeUrl } from './rules'
import type {
	FlagReason,
	IndexStatus,
	InspectedPost,
	ReportModel,
	StrikingRow
} from './types'

/** How many rows of each kind fit in the body. */
interface Limits {
	recentUnflagged: number
	striking: number
	recentFlagged: number
	needs: number
}

// Every rule number comes from config.ts so the text cannot drift (WR-04).
const NO_DATA = `No Search Analytics data in the last ${PROBE_DAYS} days.`
const NO_POSTS = `No posts published in the last ${LOOKBACK_DAYS} days.`
const STRIKING_RANGE = `${STRIKING_MIN} to ${STRIKING_MAX}`
const FOOTER =
	'Generated by .github/workflows/gsc-weekly-report.yml. Setup and rotation: docs/gsc-weekly-report-setup.md.'
const UNAVAILABLE = 'unavailable'

/**
 * Untrusted text as one inline code span: GitHub does not expand @mentions,
 * #refs or markdown inside code. Newlines collapse, backticks become quotes
 * and pipes are escaped so table cells stay intact.
 */
export function mdCode(text: string): string {
	const clean = text
		.replace(/[\r\n]+/g, ' ')
		.replace(/`/g, "'")
		.replace(/\|/g, '\\|')
	return `\`${clean}\``
}

function count(n: number): string {
	return n.toLocaleString('en-US')
}

function plural(n: number, one: string, many: string): string {
	return `${count(n)} ${n === 1 ? one : many}`
}

function table(header: string[], rows: string[][]): string[] {
	return [
		`| ${header.join(' | ')} |`,
		`| ${header.map(() => '---').join(' | ')} |`,
		...rows.map(r => `| ${r.join(' | ')} |`)
	]
}

function sizeNote(n: number): string {
	return `${plural(n, 'row', 'rows')} not shown to stay under the GitHub size limit.`
}

/** Joins blocks of lines with one blank line between them. */
function blocks(parts: string[][]): string[] {
	return parts.flatMap((part, i) => (i === 0 ? part : ['', ...part]))
}

function section(heading: string, parts: string[][]): string[] {
	return blocks([[heading], ...parts])
}

function isFlagged(post: InspectedPost): boolean {
	return post.reasons.length > 0
}

function statusOf(post: InspectedPost): IndexStatus | undefined {
	return post.outcome.ok ? post.outcome.status : undefined
}

function cell(value: string | undefined, missing: string): string {
	if (value === undefined) {
		return missing
	}
	return value === '' ? 'empty' : mdCode(value)
}

function canonicalCell(value: string | undefined, url: string): string {
	if (value !== undefined && normalizeUrl(value) === normalizeUrl(url)) {
		return 'self'
	}
	return cell(value, 'none')
}

function reasonText(reason: FlagReason, post: InspectedPost): string {
	if (reason === 'not_indexed') {
		return 'not indexed'
	}
	if (reason === 'canonical_mismatch') {
		return 'Google canonical differs'
	}
	const { outcome } = post
	if (outcome.ok || 'unexpectedResponse' in outcome) {
		return 'inspection failed (unexpected response)'
	}
	return outcome.httpStatus === null
		? 'inspection failed (network error)'
		: `inspection failed (HTTP ${outcome.httpStatus})`
}

function needsRow(post: InspectedPost): string[] {
	const status = statusOf(post)
	return [
		`[${post.path}](${post.url})`,
		String(post.daysSincePublish),
		post.reasons.map(r => reasonText(r, post)).join('; '),
		status ? cell(status.verdict, 'none') : UNAVAILABLE,
		status ? cell(status.coverageState, 'none') : UNAVAILABLE
	]
}

function recentRow(post: InspectedPost): string[] {
	const head = [mdCode(post.path), String(post.daysSincePublish)]
	const status = statusOf(post)
	if (!status) {
		return [...head, ...Array<string>(5).fill(UNAVAILABLE)]
	}
	return [
		...head,
		cell(status.verdict, 'none'),
		cell(status.coverageState, 'none'),
		status.lastCrawlTime ? mdCode(status.lastCrawlTime.slice(0, 10)) : 'never',
		canonicalCell(status.googleCanonical, post.url),
		canonicalCell(status.userCanonical, post.url)
	]
}

function strikingCells(row: StrikingRow): string[] {
	return [
		mdCode(row.query),
		mdCode(row.pagePath),
		count(row.impressions),
		count(row.clicks),
		`${(row.ctr * 100).toFixed(1)}%`,
		row.position.toFixed(1)
	]
}

function header(model: ReportModel, flagged: number): string[][] {
	const { window } = model
	const parts = [
		[`Run date: ${model.runDate} (UTC)`],
		[
			window
				? `Search Analytics window: ${window.startDate} to ${window.endDate} (Pacific dates, final data)`
				: `Search Analytics window: none (no data in the last ${PROBE_DAYS} days)`
		],
		[
			`Posts published in the last ${LOOKBACK_DAYS} days: ${model.totalRecent}. Inspected: ${model.posts.length}. Flagged: ${flagged}.`
		]
	]
	if (model.skippedByCap > 0) {
		parts.push([
			`Skipped (over the ${MAX_INSPECTIONS} per run cap): ${model.skippedByCap}.`
		])
	}
	return parts
}

function needsSection(flagged: InspectedPost[], limit: number): string[] {
	const heading = '## Needs attention'
	if (flagged.length === 0) {
		return section(heading, [['None.']])
	}
	const rows = flagged.slice(0, limit).map(needsRow)
	const parts = [
		table(['Post', 'Days since publish', 'Reason', 'Verdict', 'Coverage'], rows)
	]
	if (rows.length < flagged.length) {
		parts.push([sizeNote(flagged.length - rows.length)])
	}
	return section(heading, parts)
}

/** Newest first; drops the oldest unflagged rows before any flagged row. */
function recentSection(posts: InspectedPost[], limits: Limits): string[] {
	const heading = '## Recent posts'
	if (posts.length === 0) {
		return section(heading, [[NO_POSTS]])
	}
	let flaggedLeft = limits.recentFlagged
	let unflaggedLeft = limits.recentUnflagged
	const kept = posts.filter(p => {
		if (isFlagged(p)) {
			flaggedLeft--
			return flaggedLeft >= 0
		}
		unflaggedLeft--
		return unflaggedLeft >= 0
	})
	const parts: string[][] = []
	if (kept.length > 0) {
		parts.push(
			table(
				[
					'Post',
					'Days since publish',
					'Verdict',
					'Coverage',
					'Last crawl',
					'Google canonical',
					'User canonical'
				],
				kept.map(recentRow)
			)
		)
	}
	if (kept.length < posts.length) {
		parts.push([sizeNote(posts.length - kept.length)])
	}
	return section(heading, parts)
}

function strikingSection(model: ReportModel, limit: number): string[] {
	const heading = `## Striking distance (position ${STRIKING_RANGE})`
	if (!model.window) {
		return section(heading, [[NO_DATA]])
	}
	const { shown, total } = model.striking
	const parts: string[][] = []
	if (total === 0) {
		parts.push([`No queries at position ${STRIKING_RANGE}.`])
	} else {
		const rows = shown.slice(0, limit).map(strikingCells)
		if (rows.length > 0) {
			parts.push(
				table(
					['Query', 'Page', 'Impressions', 'Clicks', 'CTR', 'Position'],
					rows
				)
			)
		}
		if (rows.length < shown.length) {
			parts.push([sizeNote(shown.length - rows.length)])
		}
		if (total > shown.length) {
			parts.push([`${count(total - shown.length)} more not shown.`])
		}
	}
	if (model.rowLimitHit) {
		parts.push([
			`Results may be truncated at the ${count(ROW_LIMIT)} row limit.`
		])
	}
	parts.push(['Google omits anonymized queries, so these totals undercount.'])
	return section(heading, parts)
}

function brandSection(model: ReportModel): string[] {
	const heading = '## Brand'
	if (!model.brand) {
		return section(heading, [[NO_DATA]])
	}
	const { clicks, impressions, rowLimitHit } = model.brand
	const parts = [
		[
			`Brand queries matching ${BRAND_TERMS.join(' or ')}: ${plural(clicks, 'click', 'clicks')}, ${plural(impressions, 'impression', 'impressions')}.`
		]
	]
	if (rowLimitHit) {
		parts.push([
			`These totals may be incomplete because the query list hit the ${count(ROW_LIMIT)} row limit.`
		])
	}
	return section(heading, parts)
}

function compose(model: ReportModel, limits: Limits): string {
	const flagged = model.posts.filter(isFlagged)
	const body = blocks([
		...header(model, flagged.length),
		needsSection(flagged, limits.needs),
		recentSection(model.posts, limits),
		strikingSection(model, limits.striking),
		brandSection(model),
		[FOOTER]
	])
	return `${body.join('\n')}\n`
}

/**
 * Full issue body. While it is over BODY_BYTE_CAP, drop rows in priority
 * order: unflagged Recent posts, Striking distance, flagged Recent posts and
 * last of all Needs attention, so flagged posts survive longest (D15 C9).
 */
export function renderReport(model: ReportModel): string {
	const flaggedCount = model.posts.filter(isFlagged).length
	const limits: Limits = {
		recentUnflagged: model.posts.length - flaggedCount,
		striking: model.striking.shown.length,
		recentFlagged: flaggedCount,
		needs: flaggedCount
	}
	const order: Array<keyof Limits> = [
		'recentUnflagged',
		'striking',
		'recentFlagged',
		'needs'
	]
	let body = compose(model, limits)
	while (Buffer.byteLength(body, 'utf8') > BODY_BYTE_CAP) {
		const key = order.find(k => limits[k] > 0)
		if (key === undefined) {
			throw new Error('Report body is over the size cap with no rows left')
		}
		limits[key]--
		body = compose(model, limits)
	}
	return body
}
